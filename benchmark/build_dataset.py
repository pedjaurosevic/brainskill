def rag(gt_title: str, gt: str, a_title: str, a: str, b_title: str, b: str) -> dict:
    return {
        "ground_truth": {"title": gt_title, "text": gt},
        "distractors": [
            {"title": a_title, "text": a},
            {"title": b_title, "text": b},
        ],
    }


